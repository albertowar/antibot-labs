#!/usr/bin/env python3
"""
Start (or restart) a chapter lab as a copy of its workshop's starter.

    python scripts/new_lab.py workshops/01-initiation/chapters/03-headers-user-agent-and-client-hints
    python scripts/new_lab.py <chapter folder> --force     # replace an existing lab's store files

Copies demo_site/, defenses/, tools/, data/, docker-compose.yml, requirements*.txt, .env.example
and .gitignore from workshops/<NN>/starter/ into <chapter>/lab/ (never .venv, instance/,
__pycache__), creates attacks/ and solutions/, and writes a README skeleton with the
"Starts from" line if the lab has no README yet. Existing attacks/, solutions/, README.md and
chapter-added files are left alone; with --force, the starter's own files are overwritten.
"""

import argparse
import json
import os
import shutil
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
ITEMS = ["labnet.py", "demo_site", "defenses", "tools", "data", "docker-compose.yml", "requirements.txt",
         "requirements-browser.txt", ".env.example", ".gitignore"]
SKIP = {".venv", "instance", "__pycache__", "logs"}

README = """# {title}: lab

Starts from: `workshops/{ws}/starter/` (contract {contract}). Adds: see the block below.

<!-- lab-diff:start -->
<!-- lab-diff:end -->

## Rules of engagement

- **Local only, enforced in code.** Every attack script and tool reaches the store through `tools/labclient.py`,
  which asks `labnet.py` at the lab root for `DEMO_URL` and refuses anything that is not this machine (side-service
  URLs such as `REDIS_URL` too). The store's edge accepts the lab headers only from loopback.
- Source addresses are rented from `data/world.json` (documentation ranges), never invented, never real. No public
  proxy lists, no third-party sites, no real users or credentials.
- **Outbound network:** none during the rounds. Only setup needs the internet: installing packages, browsers and
  container images.

## Setup

```bash
python3.12 -m venv .venv && . .venv/bin/activate
pip install -r requirements.txt
python tools/doctor.py
python demo_site/app.py
```

## Rounds

| Round | Defense (level) | Attack | Expected |
|---|---|---|---|

## Expected results (self-check)

Generated by `python tools/verify.py --all --markdown`; do not edit by hand.
"""


def copy_item(src, dst, force):
    if os.path.isdir(src):
        for root, dirs, files in os.walk(src):
            dirs[:] = [d for d in dirs if d not in SKIP]
            rel = os.path.relpath(root, src)
            os.makedirs(os.path.join(dst, rel), exist_ok=True)
            for f in files:
                if f.endswith((".pyc", ".bak")):
                    continue
                target = os.path.join(dst, rel, f)
                if force or not os.path.exists(target):
                    shutil.copy2(os.path.join(root, f), target)
    elif force or not os.path.exists(dst):
        shutil.copy2(src, dst)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("chapter")
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    chapter = os.path.abspath(a.chapter)
    ws = os.path.relpath(chapter, ROOT).split(os.sep)[1]
    starter = os.path.join(ROOT, "workshops", ws, "starter")
    if not os.path.isdir(starter):
        sys.exit(f"{os.path.relpath(starter, ROOT)} does not exist yet (it is built from the previous capstone).")
    lab = os.path.join(chapter, "lab")
    os.makedirs(lab, exist_ok=True)
    for item in ITEMS:
        src = os.path.join(starter, item)
        if os.path.exists(src):
            copy_item(src, os.path.join(lab, item), a.force)
    for d in ("attacks", "solutions"):
        os.makedirs(os.path.join(lab, d), exist_ok=True)
    contract = json.load(open(os.path.join(starter, "STARTER.json")))["contract_version"]
    readme = os.path.join(lab, "README.md")
    if not os.path.exists(readme):
        open(readme, "w").write(README.format(title=os.path.basename(chapter), ws=ws, contract=contract))
    print(f"{os.path.relpath(lab, ROOT)} now holds the {ws} starter (contract {contract}).")
    print("Next: add defenses/<name>.py checks, demo_site/ext/<name>.py, attacks/, solutions/roundN/, fill tools/checkpoint.py ROUNDS,")
    print(f"then python scripts/lab_diff.py {os.path.relpath(lab, ROOT)} --write-readme")


if __name__ == "__main__":
    main()
