def browser_headers(kind="link", referer=None, accept_json=False):
    """A real Chrome's header block (W1 Ch4: free to forge), optionally asking for JSON."""
    h = browsers.headers_for(CHROME, kind, BASE_URL, referer)
    if accept_json:
        h = [(k, "application/json") if k == "Accept" else (k, v) for k, v in h]
    return h


def combo_list(n=1000, seed=20261014):
    """A synthetic stuffing list: the seed's 30 weak accounts hidden among strangers (email, password)."""
    rng = random.Random(seed)
    with open(WORDLIST) as fh:
        common = [ln.strip() for ln in fh if ln.strip() and not ln.startswith("#")]
    pairs = list(weak_users())
    seen = {e for e, _ in pairs}
    while len(pairs) < n:
        email = f"stranger{rng.randrange(10 ** 6):06d}@example.test"
        if email not in seen:
            seen.add(email)
            pairs.append((email, rng.choice(common)))
    rng.shuffle(pairs)
    return pairs


def map_threads(fn, items, workers=THREADS):
    with ThreadPoolExecutor(workers) as pool:
        return list(pool.map(fn, items))


