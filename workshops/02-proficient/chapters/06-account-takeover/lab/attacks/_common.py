"""
Shared plumbing for the W2 Ch6 attack scripts.

Rules of engagement, enforced in code:
  - Every script imports tools/labclient.py, which asks labnet.py (lab root) for DEMO_URL and
    refuses anything that is not this machine.
  - Source addresses are rented from data/world.json (documentation ranges) and sent as
    X-Lab-Client-IP: cloud_vm for the datacenter stuffers, residential_proxy_net for the one that
    spreads across hundreds of networks. No proxy, no real address, no third-party site.
  - Every credential is synthetic. The "breach" a stuffer replays is generated by combo_list() from
    the seed's own users (demo_site/seed.py: weak_users) and invented strangers; nothing here is,
    or was derived from, a real leak.

Each script ends by printing one JSON line for tools/checkpoint.py:
    {"attempted": 1000, "succeeded": 30, "accounts_taken_over": 30, ...}
`attempted` is what the attacker tried, `succeeded` what it got.
"""

import json
import os
import random
import sys
from concurrent.futures import ThreadPoolExecutor

LAB = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(LAB, "tools"))
import labclient  # noqa: E402  (runs the labnet guard on import)
from labclient import LabClient, world_pool  # noqa: E402
from demo_site.seed import password_for, username, weak_users  # noqa: E402

LIB_HEADERS = [("User-Agent", "python-requests/2.34.2"), ("Accept", "application/json")]
WORDLIST = os.path.join(LAB, "data", "wordlists", "passwords_top.txt")
THREADS = 16


def combo_list(n=1000, seed=20261014):
    """A synthetic stuffing list: the seed's 30 weak accounts hidden among strangers.

    The pairs are (email, password) as they would appear in a leaked combo list. Only the
    weak_users() pairs match an account in the store; the rest are `strangerNNNNNN@example.test`
    addresses that were never customers, with passwords drawn from the same wordlist.
    """
    rng = random.Random(seed)
    with open(WORDLIST) as f:
        common = [line.strip() for line in f if line.strip() and not line.startswith("#")]
    pairs = list(weak_users())
    seen = {e for e, _ in pairs}
    while len(pairs) < n:
        email = f"stranger{rng.randrange(10 ** 6):06d}@example.test"
        if email not in seen:
            seen.add(email)
            pairs.append((email, rng.choice(common)))
    rng.shuffle(pairs)
    return pairs


def login(client, email, password, **kw):
    return client.post("/api/login", json={"email": email, "password": password}, headers=LIB_HEADERS, **kw)


def is_success(r):
    try:
        return r.status_code == 200 and bool(r.json().get("ok"))
    except ValueError:
        return False


def map_threads(fn, items):
    with ThreadPoolExecutor(THREADS) as pool:
        return list(pool.map(fn, items))


def victim_signs_in(index, home_ip):
    """Setup for the infostealer rounds: the victim logs in from home on their usual device.

    Returns the victim's LabClient (its cookie jar holds the session `sid` and the device id
    `did`). The device id is fixed per victim so every attack script, and every round, sees the
    same browser. The defenses cannot tell this is "setup": it is an ordinary human login, and
    the scoreboard counts it as one.
    """
    victim = LabClient(f"human:victim:{index:02d}", ip=home_ip)
    victim.set_cookie("did", f"vicdev-{index:02d}")
    r = login(victim, username(index), password_for(index))
    if not is_success(r):
        raise SystemExit(f"setup failed: victim {index} could not sign in ({r.status_code} {r.text[:80]})")
    return victim


def report(**out):
    print(json.dumps(out))
